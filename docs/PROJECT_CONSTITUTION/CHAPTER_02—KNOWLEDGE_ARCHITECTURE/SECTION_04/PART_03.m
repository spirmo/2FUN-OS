CHAPTER_02 — KNOWLEDGE ARCHITECTURE

SECTION_04 — تعریف Knowledge Unit در معماری دانش

PART_03 — مرز میان Knowledge Unit و Concept

در معماری TANDIL، Concept و Knowledge Unit دو موجودیت مکمل هستند، اما هیچ‌گاه نباید به‌جای یکدیگر استفاده شوند.

اگر این دو موجودیت با یکدیگر ادغام شوند، حقیقت و تبیین حقیقت از هم قابل تفکیک نخواهند بود و معماری دانش به‌تدریج قابلیت توسعه و نگهداری خود را از دست خواهد داد.

---

Concept چیست؟

Concept نماینده یک حقیقت بنیادین است.

Concept فقط مشخص می‌کند که «چه چیزی حقیقت است.»

Concept فاقد توضیحات، مثال‌ها، تحلیل‌ها و منابع علمی است.

هویت آن باید در تمام طول عمر سامانه پایدار باقی بماند.

---

Knowledge Unit چیست؟

Knowledge Unit دانش پیرامون همان حقیقت را حمل می‌کند.

Knowledge Unit توضیح می‌دهد:

- حقیقت چگونه تعریف می‌شود.
- چگونه تفسیر می‌شود.
- چه شواهدی آن را پشتیبانی می‌کنند.
- چگونه آموزش داده می‌شود.
- چگونه در موقعیت‌های مختلف به‌کار می‌رود.

بنابراین، Knowledge Unit پاسخ‌گوی پرسش «این حقیقت را چگونه می‌توان فهمید؟» است.

---

تفاوت بنیادی

Concept هویت حقیقت است.

Knowledge Unit بیان حقیقت است.

Concept تغییر نمی‌کند.

Knowledge Unit می‌تواند تکمیل، اصلاح، بازنویسی یا غنی‌تر شود.

Concept یکتا است.

Knowledge Unit می‌تواند برای یک Concept به تعداد نامحدود وجود داشته باشد.

---

مثال

Concept:

عدالت

Knowledge Unitهای مرتبط:

- تعریف فلسفی عدالت
- نظریه‌های عدالت در علوم سیاسی
- عدالت در اقتصاد
- عدالت در حقوق
- عدالت از دیدگاه روان‌شناسی
- مطالعات تجربی درباره عدالت
- نمونه‌های تاریخی عدالت

در این مثال، تمام Knowledge Unitها درباره یک حقیقت صحبت می‌کنند، اما هیچ‌کدام خود حقیقت نیستند.

---

اصل استقلال

اگر تمام Knowledge Unitهای مربوط به یک Concept حذف شوند، Concept همچنان وجود دارد.

اگر Knowledge Unitهای جدیدی ایجاد شوند، Concept تغییری نمی‌کند.

زیرا Concept حامل حقیقت است و Knowledge Unit حامل دانش درباره آن حقیقت.

---

اصل معماری

بر اساس قانون اساسی TANDIL:

Concept مرجع حقیقت است.

Knowledge Unit مرجع دانش درباره حقیقت است.

این تفکیک، امکان رشد نامحدود شبکه دانشی را بدون ایجاد نسخه‌های متعدد از حقیقت فراهم می‌کند و یکی از مهم‌ترین اصول پایداری معماری دانش در پروژه TANDIL محسوب می‌شود.
